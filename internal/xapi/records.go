package xapi

import (
	"fmt"
	"strings"
	"time"
)

// Only the fields this connector reads. XAPI returns int64 values as JSON numbers.

type VBDRecord struct {
	UUID       string `json:"uuid"`
	VDI        string `json:"VDI"`
	Userdevice string `json:"userdevice"`
	Bootable   bool   `json:"bootable"`
	Mode       string `json:"mode"`
	Type       string `json:"type"`
	Empty      bool   `json:"empty"`
}

type VDIRecord struct {
	UUID            string `json:"uuid"`
	NameLabel       string `json:"name_label"`
	NameDescription string `json:"name_description"`
	SR              string `json:"SR"`
	VirtualSize     int64  `json:"virtual_size"`
	SnapshotOf      string `json:"snapshot_of"`
}

type VIFRecord struct {
	Device           string `json:"device"`
	Network          string `json:"network"`
	MAC              string `json:"MAC"`
	MACAutogenerated bool   `json:"MAC_autogenerated"`
	MTU              int64  `json:"MTU"`
}

type NetworkRecord struct {
	UUID      string `json:"uuid"`
	NameLabel string `json:"name_label"`
}

// MetaVersion is the version of the vm.json layout.
const MetaVersion = 1

// MetaFilename is the name of the per-VM metadata record.
const MetaFilename = "vm.json"

// VMMeta is the content of vm.json: what a restore needs to rebuild the VM.
type VMMeta struct {
	Version int `json:"version"`
	// VM is the VM record as returned by VM.get_record, references included.
	VM    map[string]any `json:"vm"`
	Disks []DiskMeta     `json:"disks"`
	VIFs  []VIFMeta      `json:"vifs"`
}

type DiskMeta struct {
	File            string `json:"file"` // record name next to vm.json
	VDIUUID         string `json:"vdi_uuid"`
	NameLabel       string `json:"name_label"`
	NameDescription string `json:"name_description"`
	VirtualSize     int64  `json:"virtual_size"`
	SRUUID          string `json:"sr_uuid"`
	Userdevice      string `json:"userdevice"`
	Bootable        bool   `json:"bootable"`
	Mode            string `json:"mode"`
}

type VIFMeta struct {
	Device           string `json:"device"`
	MAC              string `json:"mac"`
	MACAutogenerated bool   `json:"mac_autogenerated"`
	MTU              int64  `json:"mtu"`
	NetworkUUID      string `json:"network_uuid"`
	NetworkName      string `json:"network_name"`
}

// DiskFilename is the record name of a disk: stable across backups, since it uses
// the original VDI's UUID, not the snapshot's.
func DiskFilename(userdevice, vdiUUID string) string {
	return fmt.Sprintf("%s-%s.raw", userdevice, vdiUUID)
}

// ParseDiskFilename returns the VDI UUID from a disk record name.
func ParseDiskFilename(name string) (string, bool) {
	stem, ok := strings.CutSuffix(name, ".raw")
	if !ok {
		return "", false
	}
	_, uuid, ok := strings.Cut(stem, "-")
	if !ok || uuid == "" {
		return "", false
	}
	return uuid, true
}

// ParseTime parses XAPI's datetime format, as found in snapshot_time.
func ParseTime(s string) (time.Time, error) {
	for _, layout := range []string{"20060102T15:04:05Z", "20060102T15:04:05Z07:00", time.RFC3339} {
		if t, err := time.Parse(layout, s); err == nil {
			return t, nil
		}
	}
	return time.Time{}, fmt.Errorf("unrecognised XAPI time %q", s)
}
